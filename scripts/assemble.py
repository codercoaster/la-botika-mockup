"""Stitch sections/*.html into the root pages, the way Shopify renders a layout +
JSON template. Dev convenience only — the generated pages are committed, so the
site runs and deploys with no build step.

  layout/theme.html     page shell; {{ content_for_layout }}, {{ page_title }}
  templates/<page>.html list of section markers:
                          <!-- @section product-rail {"id": "ofertas", "title": "Ofertas"} -->
  sections/<name>.html  section markup; {{ section.id }} and {{ section.settings.x }}
                        placeholders, plus its own <link>/<script> tags (hoisted + deduped)

Run from the repo root:  python3 -I scripts/assemble.py
"""
import glob
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MARKER = re.compile(r"<!--\s*@section\s+([\w-]+)\s*(\{.*?\})?\s*-->", re.S)
SNIPPET = re.compile(r"<!--\s*@snippet\s+([\w-]+)\s*-->")
ASSET_TAG = re.compile(r'^\s*(<link rel="stylesheet"[^>]*>|<script [^>]*src="[^"]*"[^>]*></script>)\s*\n', re.M)


def read(path):
    with open(os.path.join(ROOT, path)) as f:
        return f.read()


def render_section(name, settings, assets):
    html = read(f"sections/{name}.html")
    section_id = settings.get("id", name)

    def tag(m):
        if m.group(1) not in assets:
            assets.append(m.group(1))
        return ""

    html = ASSET_TAG.sub(tag, html)
    html = html.replace("{{ section.id }}", section_id)
    html = re.sub(r"\{\{\s*section\.settings\.(\w+)\s*\}\}", lambda m: str(settings.get(m.group(1), "")), html)
    html = re.sub(r"^<!--.*?-->\n", "", html, flags=re.S)  # drop the porting note at the top
    return (f'<div id="shopify-section-{section_id}" class="shopify-section section-{name}">\n'
            f"{html.strip()}\n</div>")


def main():
    layout = read("layout/theme.html")
    for template_path in sorted(glob.glob(os.path.join(ROOT, "templates", "*.html"))):
        page = os.path.basename(template_path)
        assets = []
        expand = lambda src: MARKER.sub(
            lambda m: render_section(m.group(1), json.loads(m.group(2) or "{}"), assets), src)

        template = read(f"templates/{page}")
        title = re.search(r"<!--\s*@title\s+(.*?)\s*-->", template).group(1)
        template = re.sub(r"<!--\s*@title.*?-->\n?", "", template)

        html = expand(layout.replace("{{ content_for_layout }}", template.strip()))
        html = SNIPPET.sub(lambda m: re.sub(r"^<!--.*?-->\n", "", read(f"snippets/{m.group(1)}.html"), flags=re.S).strip(), html)
        css = [a for a in assets if a.startswith("<link")]
        js = [a for a in assets if a.startswith("<script")]
        html = html.replace("{{ page_title }}", title)
        html = html.replace("{{ section_styles }}", "\n  ".join(css))
        html = html.replace("{{ section_scripts }}", "\n  ".join(js))

        with open(os.path.join(ROOT, page), "w") as f:
            f.write(html.replace("<!doctype html>", "<!doctype html>\n<!-- Generated by scripts/assemble.py from layout/, templates/ and sections/ -->", 1))
        print(f"wrote {page}: {html.count('shopify-section-')} sections")


if __name__ == "__main__":
    main()
